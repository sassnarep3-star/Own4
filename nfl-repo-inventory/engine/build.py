"""Render the NFL repo inventory pages from data/*.json (stdlib only, deterministic).

Run: python3 nfl-repo-inventory/engine/build.py
Inputs: data/inventory.json, data/verifier_runs.json, data/flags.json, data/official_reads.json
Outputs: index.html, pages/inventory.html, pages/verifier-runs.html, pages/flagged.html
"""
import html
import json
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(HERE, "data")


def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as fh:
        return json.load(fh)


def esc(v):
    return "" if v is None else html.escape(str(v), quote=True)


def link(url, text=None):
    if not url:
        return '<span class="unverified">blank: unverified</span>'
    return f'<a href="{esc(url)}">{esc(text or url)}</a>'


CSS = """
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:0;color:#1d1d1f;background:#f7f7f8;line-height:1.45}
header{background:#13294b;color:#fff;padding:18px 24px}
header a{color:#cfe3ff}
main{max-width:1200px;margin:0 auto;padding:20px 24px 48px}
h1{font-size:1.6rem;margin:6px 0 8px} h2{font-size:1.2rem;margin-top:28px}
.tiles{display:flex;flex-wrap:wrap;gap:12px;margin:14px 0}
.tile{background:#fff;border:1px solid #dcdfe4;border-radius:8px;padding:12px 16px;min-width:150px}
.tile b{display:block;font-size:1.5rem}
table{border-collapse:collapse;width:100%;background:#fff;font-size:.9rem;margin:10px 0}
th,td{border:1px solid #dcdfe4;padding:6px 8px;text-align:left;vertical-align:top}
th{background:#eef1f6}
.unverified{color:#8a4b00;font-style:italic}
.note{background:#fff8e6;border:1px solid #f2d68b;border-radius:8px;padding:10px 14px;margin:12px 0}
.fail{color:#a40000;font-weight:600} .ok{color:#136b2c;font-weight:600}
nav a{margin-right:14px}
footer{color:#555;font-size:.85rem;margin-top:30px}
"""


def page(title, body, active):
    # active is the page's path relative to this namespace root ("index.html" or "pages/x.html")
    in_pages = active.startswith("pages/")
    def href(target):
        # target is relative to the namespace root; convert it to be relative to the current page
        if in_pages and target.startswith("pages/"):
            return target[len("pages/"):]
        if in_pages:
            return "../" + target
        return target
    nav = [("index.html", "Overview"), ("pages/inventory.html", "Namespace inventory"),
           ("pages/verifier-runs.html", "Verifier runs"), ("pages/flagged.html", "Flagged for Review")]
    links = "".join(
        f'<a href="{href(h)}"{" aria-current=page" if h == active else ""}>{t}</a>' for h, t in nav)
    links += f'<a href="{href("../index.html")}">Root site</a>'
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(title)} · NFL repo inventory</title>
<style>{CSS}</style></head>
<body>
<header><nav>{links}</nav></header>
<main>
{body}
<footer>Generated by nfl-repo-inventory/engine/build.py from data/*.json. Repository rows link to the repository (the evidence itself). NFL facts link to nfl.com. Verifier PASS means internal consistency and link integrity, not verified official values.</footer>
</main></body></html>
"""


def overview(inv, runs, flags, reads):
    rows = inv["rows"]
    n_ver = sum(1 for r in rows if r["verifier_path"])
    n_pass = sum(1 for r in runs["runs"] if r["exit"] == 0)
    n_fail = sum(1 for r in runs["runs"] if r["exit"] != 0)
    n_noroot = sum(1 for r in rows if not r["linked_from_root_index"])
    tiles = [
        (inv["namespace_count"], "nfl* namespaces"),
        (sum(r["tracked_files"] for r in rows), "tracked files"),
        (n_ver, "with a verifier"),
        (n_pass, "verifier runs passing"),
        (n_fail, "verifier runs not passing"),
        (n_noroot, "not linked from root"),
        (len(flags["flags"]), "flags for review"),
    ]
    tile_html = "".join(f'<div class="tile"><b>{esc(v)}</b>{esc(l)}</div>' for v, l in tiles)
    read_rows = "".join(
        f"<tr><td>{esc(r['what'])}</td><td>{esc(r['observed'])}</td><td>{link(r['url'], r['url'])}</td></tr>"
        for r in reads["rows"])
    body = f"""
<h1>NFL repository inventory and verifier audit</h1>
<p>A machine-generated map of the {inv['namespace_count']} <code>nfl*</code> namespaces in this repository, taken at commit <code>{esc(inv['generated_for_commit'])}</code> on {esc(inv['generated_on'])}. It answers three questions: which pages exist, which verifier checks them, and what the verifier returned on a clean export.</p>
<div class="tiles">{tile_html}</div>
<div class="note"><b>Read this first.</b> A verifier PASS means a namespace's links resolve, its rows carry a source link, and its numbers agree with its own files. It does not re-check official NFL values. See flag F07.</div>
<h2>Official read on 2026-11-19</h2>
<p>Fetched by the session on the date above. Only the rows listed here were read. No Week 11 injury row was transcribed into any table (see flag F09).</p>
<table><tr><th>What was read</th><th>What the page showed</th><th>Source</th></tr>{read_rows}</table>
<h2>Decisions needed before anything else is trusted</h2>
<ol>
<li>Which NFL namespace is canonical for each topic (flag F01).</li>
<li>Which executive summary is current (flag F02).</li>
<li>Whether the stored Week 11 raw capture is parsed and re-verified, and by when (flags F08, F09).</li>
<li>Whether the round-1 verifier is deleted or kept as retired (flag F05).</li>
</ol>
<p>Full list: <a href="pages/flagged.html">Flagged for Review</a>. Per-namespace detail: <a href="pages/inventory.html">Namespace inventory</a>. Verifier outputs: <a href="pages/verifier-runs.html">Verifier runs</a>.</p>
"""
    return page("Overview", body, "index.html")


def inventory_page(inv):
    trs = []
    for r in inv["rows"]:
        entry = link(r["live_url"], r["entry_page"]) if r["live_url"] else (
            '<span class="unverified">no entry page</span>')
        ver = f"<code>{esc(r['verifier_path'])}</code>" if r["verifier_path"] else '<span class="unverified">none</span>'
        if r["verifier_exit"] is None:
            ran = '<span class="unverified">not run</span>'
        elif r["verifier_exit"] == 0:
            ran = '<span class="ok">exit 0</span>'
        else:
            ran = f'<span class="fail">exit {esc(r["verifier_exit"])}</span>'
        root = "yes" if r["linked_from_root_index"] else '<span class="fail">no</span>'
        trs.append(
            f"<tr><td>{link(r['github_url'], r['namespace'])}</td><td>{esc(r['tracked_files'])}</td>"
            f"<td>{entry}</td><td>{ver}</td><td>{ran}</td><td>{root}</td>"
            f"<td>{esc(r['last_commit'])}</td></tr>")
    body = f"""
<h1>Namespace inventory</h1>
<p>One row per <code>nfl*</code> directory. Namespace links go to the GitHub folder (the evidence). "Root" means the root <code>index.html</code> refers to the namespace. The root page is not edited in this session. "Last commit" is the latest commit touching the folder; for most rows it is e322a32, a sync commit that touched many folders, so it does not show per-namespace history.</p>
<table>
<tr><th>Namespace (source)</th><th>Tracked files</th><th>Entry page</th><th>Verifier</th><th>Verifier run</th><th>Linked from root</th><th>Last commit</th></tr>
{''.join(trs)}
</table>
"""
    return page("Namespace inventory", body, "pages/inventory.html")


def runs_page(runs):
    trs = []
    for r in runs["runs"]:
        cls = "ok" if r["exit"] == 0 else "fail"
        trs.append(
            f"<tr><td>{esc(r['namespace'])}</td><td>{link('https://github.com/sassnarep3-star/Own4/blob/main/' + r['verifier'], r['verifier'])}</td>"
            f"<td class='{cls}'>{esc(r['exit'])}</td><td>{esc(r['last_line'])}</td></tr>")
    body = f"""
<h1>Verifier runs</h1>
<p>{esc(runs['method'])}</p>
<table><tr><th>Namespace</th><th>Verifier (source)</th><th>Exit</th><th>Last output line</th></tr>
{''.join(trs)}
</table>
"""
    return page("Verifier runs", body, "pages/verifier-runs.html")


def flags_page(flags):
    items = []
    for f in flags["flags"]:
        srcs = " · ".join(link(u, u.split("/blob/main/")[-1] if "/blob/main/" in u else u) for u in f["evidence"])
        items.append(
            f"<tr><td>{esc(f['id'])}</td><td><b>{esc(f['title'])}</b><br>{esc(f['detail'])}</td>"
            f"<td>{srcs}</td><td>{esc(f['owner_decision'])}</td><td>needs review</td></tr>")
    body = f"""
<h1>Flagged for Review</h1>
<p>{esc(flags['note'])} Nothing here blocks the merge. Each flag stays open until the owner decides.</p>
<table><tr><th>ID</th><th>Irregularity</th><th>Source links</th><th>Decision needed</th><th>Status</th></tr>
{''.join(items)}
</table>
"""
    return page("Flagged for Review", body, "pages/flagged.html")


def main():
    inv = load("inventory.json")
    runs = load("verifier_runs.json")
    flags = load("flags.json")
    reads = load("official_reads.json")
    outputs = {
        "index.html": overview(inv, runs, flags, reads),
        os.path.join("pages", "inventory.html"): inventory_page(inv),
        os.path.join("pages", "verifier-runs.html"): runs_page(runs),
        os.path.join("pages", "flagged.html"): flags_page(flags),
    }
    for rel, text in outputs.items():
        path = os.path.join(HERE, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote", rel)


if __name__ == "__main__":
    main()
