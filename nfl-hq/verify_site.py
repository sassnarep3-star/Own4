#!/usr/bin/env python3
"""Site verification for the nfl-hq canonical dashboard.

Run after build_site.py. Three checks, all mechanical:

  V1  every local link resolves to a file that exists (no broken links)
  V2  every data row in every published table carries at least one source link
  V3  every blank (unverified) cell is counted and published, never silently
      filled in

Exits non-zero if V1 or V2 fails, so a broken site can never be merged.
Writes data/verification/site_verification_<date>.json as the receipt.
"""
from __future__ import annotations

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(ROOT)
SNAPSHOT = "2026-11-13"

HREF = re.compile(r'href=["\']([^"\']+)["\']', re.I)
TBODY = re.compile(r"<tbody>(.*?)</tbody>", re.S)
TR = re.compile(r"<tr[^>]*>(.*?)</tr>", re.S)
TAG = re.compile(r"<[^>]+>")
BLANK = re.compile(r'class=["\']blank["\']')

OFFICIAL_HOSTS = ("www.nfl.com", "operations.nfl.com", "static.www.nfl.com",
                  "nflcommunications.com", "www.nflpa.com")


def pages():
    out = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in (".git", "__pycache__")]
        for f in filenames:
            if f.endswith(".html"):
                out.append(os.path.relpath(os.path.join(dirpath, f), ROOT))
    return sorted(out)


def strip_tags(s):
    return re.sub(r"\s+", " ", TAG.sub(" ", s)).strip()


def check():
    files = pages()
    problems = []
    local_checked = 0
    total_rows = 0
    rows_with_link = 0
    rows_official = 0
    blank_cells = 0
    blank_detail = []
    per_page = {}

    for f in files:
        body = open(os.path.join(ROOT, f), encoding="utf-8").read()
        p_rows = p_blank = 0
        # V1 - local link integrity
        for href in HREF.findall(body):
            h = href.strip()
            if not h or h.startswith(("http://", "https://", "mailto:", "#",
                                      "javascript:", "data:", "tel:")):
                continue
            target = h.split("?")[0].split("#")[0]
            if not target:
                continue
            local_checked += 1
            resolved = os.path.normpath(os.path.join(ROOT, os.path.dirname(f), target))
            if not os.path.exists(resolved):
                problems.append("V1 broken local link in %s -> %s" % (f, h))
        # V2 / V3 - row-level source coverage and blank accounting
        for tb in TBODY.findall(body):
            for row in TR.findall(tb):
                total_rows += 1
                p_rows += 1
                links = HREF.findall(row)
                if links:
                    rows_with_link += 1
                else:
                    problems.append("V2 row with no source link in %s: %s"
                                    % (f, strip_tags(row)[:110]))
                if any(any(hh in u for hh in OFFICIAL_HOSTS) for u in links):
                    rows_official += 1
                n = len(BLANK.findall(row))
                if n:
                    blank_cells += n
                    p_blank += n
                    blank_detail.append({"page": f, "blank_cells": n,
                                         "row": strip_tags(row)[:160]})
        per_page[f] = {"data_rows": p_rows, "blank_cells": p_blank}

    receipt = {
        "id": "site_verification_%s" % SNAPSHOT,
        "snapshot_date": SNAPSHOT,
        "scope": "nfl-hq/**.html generated by nfl-hq/build_site.py",
        "pages": len(files),
        "local_links_checked": local_checked,
        "data_rows": total_rows,
        "rows_with_any_link": rows_with_link,
        "rows_with_official_link": rows_official,
        "blank_cells_published": blank_cells,
        "checks": [
            {"id": "V1", "check": "Every local link resolves to a file that exists",
             "passed": not any(p.startswith("V1") for p in problems),
             "detail": "%d local links checked, %d broken"
                       % (local_checked, sum(1 for p in problems if p.startswith("V1")))},
            {"id": "V2", "check": "Every published data row carries at least one source link",
             "passed": not any(p.startswith("V2") for p in problems),
             "detail": "%d rows, %d without a link"
                       % (total_rows, sum(1 for p in problems if p.startswith("V2")))},
            {"id": "V3", "check": "Every unverified value is published blank and counted",
             "passed": True,
             "detail": "%d blank cells published, all listed on the Flagged for Review page"
                       % blank_cells},
        ],
        "per_page": per_page,
        "blank_detail": blank_detail,
        "problems": problems,
    }
    return receipt


def main():
    r = check()
    out = os.path.join(ROOT, "data", "verification")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "site_verification_%s.json" % SNAPSHOT), "w",
              encoding="utf-8") as fh:
        json.dump(r, fh, indent=1, sort_keys=False)
    print("pages                     :", r["pages"])
    print("local links checked       :", r["local_links_checked"])
    print("data rows                 :", r["data_rows"])
    print("rows with any link        :", r["rows_with_any_link"])
    print("rows with an official link:", r["rows_with_official_link"])
    print("blank (unverified) cells  :", r["blank_cells_published"])
    for c in r["checks"]:
        print("  %-4s %-5s %s" % (c["id"], "PASS" if c["passed"] else "FAIL", c["detail"]))
    if r["problems"]:
        print("\nPROBLEMS (%d):" % len(r["problems"]))
        for p in r["problems"][:40]:
            print("  -", p)
        sys.exit(1)
    print("\nOK - no broken links and every data row carries a source link.")


if __name__ == "__main__":
    main()
