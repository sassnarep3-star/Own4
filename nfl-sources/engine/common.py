# ---------------------------------------------------------------- io
def read_text(path):
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def read_json(path):
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def write_json(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, indent=1, sort_keys=False, ensure_ascii=False)
        fh.write("\n")


def write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def sha256_text(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_file(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


# ---------------------------------------------------------------- math
def phi(z):
    return 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))


def inv_phi(p):
    """Inverse standard normal CDF (Acklam's rational approximation, |rel err| < 1.2e-9)."""
    if not (0.0 < p < 1.0):
        raise ValueError("inv_phi domain")
    a = [-3.969683028665376e+01, 2.209460984245205e+02, -2.759285104469687e+02,
         1.383577518672690e+02, -3.066479806614716e+01, 2.506628277459239e+00]
    b = [-5.447609879822406e+01, 1.615858368580409e+02, -1.556989798598866e+02,
         6.680131188771972e+01, -1.328068155288572e+01]
    c = [-7.784894002430293e-03, -3.223964580411365e-01, -2.400758277161838e+00,
         -2.549732539343734e+00, 4.374664141464968e+00, 2.938163982698783e+00]
    d = [7.784695709041462e-03, 3.224671290700398e-01, 2.445134137142996e+00,
         3.754408661907416e+00]
    plow, phigh = 0.02425, 1 - 0.02425
    if p < plow:
        q = math.sqrt(-2 * math.log(p))
        return (((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) / \
               ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1)
    if p > phigh:
        q = math.sqrt(-2 * math.log(1 - p))
        return -(((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) / \
               ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1)
    q = p - 0.5
    r = q * q
    return (((((a[0] * r + a[1]) * r + a[2]) * r + a[3]) * r + a[4]) * r + a[5]) * q / \
           (((((b[0] * r + b[1]) * r + b[2]) * r + b[3]) * r + b[4]) * r + 1)


def solve(matrix, rhs):
    """Gaussian elimination with partial pivoting. Returns x for A x = b (mutates copies)."""
    n = len(matrix)
    a = [row[:] + [rhs[i]] for i, row in enumerate(matrix)]
    for col in range(n):
        piv = max(range(col, n), key=lambda r: abs(a[r][col]))
        if abs(a[piv][col]) < 1e-12:
            raise ValueError("singular system at column %d" % col)
        a[col], a[piv] = a[piv], a[col]
        pv = a[col][col]
        for j in range(col, n + 1):
            a[col][j] /= pv
        for r in range(n):
            if r == col:
                continue
            f = a[r][col]
            if f:
                for j in range(col, n + 1):
                    a[r][j] -= f * a[col][j]
    return [a[i][n] for i in range(n)]


def mean(xs):
    return math.fsum(xs) / len(xs) if xs else float("nan")


def sd(xs):
    if len(xs) < 2:
        return float("nan")
    m = mean(xs)
    return math.sqrt(math.fsum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def rms(xs):
    return math.sqrt(math.fsum(x * x for x in xs) / len(xs)) if xs else float("nan")


def pearson(xs, ys):
    n = len(xs)
    if n < 3:
        return None
    mx, my = mean(xs), mean(ys)
    sxy = math.fsum((x - mx) * (y - my) for x, y in zip(xs, ys))
    sxx = math.fsum((x - mx) ** 2 for x in xs)
    syy = math.fsum((y - my) ** 2 for y in ys)
    if sxx <= 0 or syy <= 0:
        return None
    return sxy / math.sqrt(sxx * syy)


def p_two_sided(r, n):
    """Two-sided p from Student t with n-2 df, evaluated with the normal approximation.

    Disclosed as an approximation: the site never prints p to more than 4 decimals and the
    interval is what carries the decision.
    """
    if r is None or n < 3 or abs(r) >= 1.0:
        return None if r is None else 0.0
    t = r * math.sqrt((n - 2) / (1 - r * r))
    return 2.0 * (1.0 - phi(abs(t)))


def fisher_ci(r, n, z=1.959963985):
    if r is None or n < 4 or abs(r) >= 1.0:
        return None
    zr = 0.5 * math.log((1 + r) / (1 - r))
    se = 1.0 / math.sqrt(n - 3)
    lo, hi = zr - z * se, zr + z * se
    return [math.tanh(lo), math.tanh(hi)]


def percentile(sorted_xs, q):
    if not sorted_xs:
        return None
    if len(sorted_xs) == 1:
        return sorted_xs[0]
    pos = (len(sorted_xs) - 1) * q
    lo = int(math.floor(pos))
    hi = min(lo + 1, len(sorted_xs) - 1)
    frac = pos - lo
    return sorted_xs[lo] * (1 - frac) + sorted_xs[hi] * frac


def cluster_bootstrap_ci(rows, stat, n_boot=2000, seed=SEED, alpha=0.05):
    """Percentile bootstrap resampling whole weeks (a week is a game cluster)."""
    weeks = sorted({r["week"] for r in rows})
    if len(weeks) < 2:
        return None
    by_week = {w: [r for r in rows if r["week"] == w] for w in weeks}
    rng = random.Random(seed)
    out = []
    for _ in range(n_boot):
        sample = []
        for _ in range(len(weeks)):
            sample.extend(by_week[rng.choice(weeks)])
        v = stat(sample)
        if v is not None and not (isinstance(v, float) and math.isnan(v)):
            out.append(v)
    if len(out) < 10:
        return None
    out.sort()
    return [percentile(out, alpha / 2), percentile(out, 1 - alpha / 2)]


def american_from_prob(p):
    """Fair American odds implied by a probability (no vig)."""
    if p <= 0 or p >= 1:
        return None
    if p >= 0.5:
        return int(round(-100.0 * p / (1 - p)))
    return int(round(100.0 * (1 - p) / p))


def fmt(x, nd=4):
    if x is None:
        return ""
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, int):
        return str(x)
    if isinstance(x, float):
        if x != x:
            return ""
        return ("%." + str(nd) + "f") % x
    return str(x)
