def g(status, evidence, source):
    return {"status": status, "evidence": evidence, "source": source}


def strategy(sid, family, name, hypothesis, inputs, gates, metrics, sources, note):
    statuses = [v["status"] for v in gates.values()]
    if all(s == P for s in statuses):
        verdict = "VALIDATED"
    elif U in statuses:
        verdict = "NOT VALIDATED (unverified data)"
    else:
        verdict = "NOT VALIDATED (gate failure)"
    return {
        "id": sid, "family": family, "name": name, "hypothesis": hypothesis,
        "inputs": inputs, "gates": gates, "verdict": verdict,
        "roi": None, "closing_line_value": None, "net_profit": None,
        "reward": None, "metrics": metrics, "sources": sources, "note": note,
        "blank_fields": ["roi", "closing_line_value", "net_profit", "reward"],
        "unverified": True,
    }


