def page(name, title, body, active=None):
    nav = []
    for href, label in NAV:
        cls = ' class="on"' if href == (active or name) else ""
        nav.append(f'<a href="{href}"{cls}>{label}</a>')
    doc = f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)} · Own4 NBA Signal Pipeline</title>
<style>{CSS}</style></head>
<body>
<header><h1>NBA Signal Pipeline</h1><span class="sub">session 75685c60 · verified data · own-line engine · official sources only</span>
<nav>{''.join(nav)}</nav></header>
<main>
{body}
</main>
<footer>Generated by scripts/build_pipeline_site.py from verified datasets ·
<a href="../index.html">Repo home</a> · <a href="../lab/index.html">Data Lab</a> · <a href="../docs/index.html">Research Docs</a> ·
every table row links its source · unverified values are blank and flagged</footer>
</body></html>"""
    with open(os.path.join(OUT, name), "w") as f:
        f.write(doc)


def blank(title):
    return f'<span class="blank" title="{html.escape(title)}">—</span>'


def src(url, label="source"):
    return f'<a href="{html.escape(url)}" rel="noopener">{html.escape(label)}</a>'


